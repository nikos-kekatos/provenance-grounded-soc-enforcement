"""Grouped bar chart of the live retraction runs (2026-10-27).
Reads ../results/live_ext_summary.json (written by live_ext.py analyze); writes ../retract_fig.tex
(pgfplots) and ../retract_macros.tex. Pools the *_retract tags of all models.

  python3 make_retract_fig.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
S = json.load(open(os.path.join(HERE, "..", "results", "live_ext_summary.json")))
tags = sorted(t for t in S if t.endswith("_retract"))
POL = [("rv", "trace monitor", "black!80"), ("backend", "stateful back end", "black!45"),
       ("percall_db", "back-end per-call", "black!12")]
agg = {}
for mode in ("notified", "silent"):
    d = {k: sum(S[t][mode][k] for t in tags) for k in S[tags[0]][mode]}
    agg[mode] = d

def pct(k, n):
    return 100.0 * k / n if n else 0.0

lines = [r"% generated by harness/make_retract_fig.py from results/live_ext_summary.json; do not edit",
         r"\begin{tikzpicture}",
         r"\begin{axis}[ybar=1pt, bar width=9pt, scale only axis, width=0.8\linewidth, height=3.0cm, ymin=0, ymax=150,",
         r"  ytick={0,25,50,75,100}, ylabel={dependent calls flagged (\%)},",
         r"  symbolic x coords={notified,silent}, xtick=data, enlarge x limits=0.35,",
         r"  xticklabels={change notified in the trace, change in the back end only},",
         r"  label style={font=\footnotesize}, tick label style={font=\footnotesize},",
         r"  nodes near coords, point meta=explicit symbolic,",
         r"  every node near coord/.append style={font=\scriptsize, rotate=90, anchor=west},",
         r"  legend image code/.code={\draw[#1] (0cm,-0.08cm) rectangle (0.22cm,0.12cm);},",
         r"  legend style={font=\scriptsize, draw=none, fill=none, at={(0.5,1.02)}, anchor=south, legend columns=3,",
         r"    /tikz/every even column/.append style={column sep=5pt}},",
         r"  axis lines*=left, tick align=outside]"]
for key, name, col in POL:
    pts = " ".join(f"({m},{pct(agg[m][key + '_refuse_dep'], agg[m]['dep_calls']):.1f}) "
                   f"[{agg[m][key + '_refuse_dep']}/{agg[m]['dep_calls']}]" for m in ("notified", "silent"))
    lines.append(rf"\addplot[fill={col}, draw=black] coordinates {{{pts}}};")
    lines.append(rf"\addlegendentry{{{name}}}")
lines += [r"\end{axis}", r"\end{tikzpicture}"]
open(os.path.join(HERE, "..", "retract_fig.tex"), "w").write("\n".join(lines) + "\n")

M = {"RtModels": len(tags)}
for m, t in (("notified", "Not"), ("silent", "Sil")):
    a = agg[m]
    M.update({f"Rt{t}Eps": a["episodes"], f"Rt{t}StaleEps": a["stale_eps"], f"Rt{t}Relook": a["relooked"],
              f"Rt{t}Calls": a["stale_calls"], f"Rt{t}Rv": a["rv_refuse_stale"],
              f"Rt{t}Be": a["backend_refuse_stale"], f"Rt{t}Pc": a["percall_db_refuse_stale"],
              f"Rt{t}Dep": a["dep_calls"], f"Rt{t}RvDep": a["rv_refuse_dep"], f"Rt{t}BeDep": a["backend_refuse_dep"],
              f"Rt{t}PcDep": a["percall_db_refuse_dep"]})
with open(os.path.join(HERE, "..", "retract_macros.tex"), "w") as f:
    f.write("% generated by harness/make_retract_fig.py from results/live_ext_summary.json; do not edit\n")
    for k, v in M.items():
        f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(json.dumps(agg, indent=1)); print(M)
